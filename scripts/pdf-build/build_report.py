FRONT_PAGES = 2  # TOC spans pages 1-2 (front matter)

class TocDocTemplate(SimpleDocTemplate):
    def afterFlowable(self, flowable):
        if hasattr(flowable, "bookmark_name"):
            level = getattr(flowable, "bookmark_level", 0)
            text = getattr(flowable, "bookmark_text", "")
            key = getattr(flowable, "bookmark_key", "")
            # TOC shows body-relative page numbers (body starts at 1 after front matter)
            self.notify("TOCEntry", (level, text, max(1, self.page - FRONT_PAGES), key))

def on_page(canvas, doc):
    canvas.saveState()
    canvas.setFont("FreeSerif", 7.5)
    canvas.setFillColor(TEXT_MUTED)
    canvas.drawString(MARGIN, PAGE_H - 0.52 * inch, "FOOTPRINTX  ·  PRODUCT REQUIREMENTS DOCUMENT")
    canvas.setStrokeColor(ACCENT)
    canvas.setLineWidth(1.1)
    canvas.line(MARGIN, PAGE_H - 0.60 * inch, PAGE_W - MARGIN, PAGE_H - 0.60 * inch)
    canvas.setFont("FreeSerif", 9)
    canvas.setFillColor(TEXT_MUTED)
    roman = {1: "i", 2: "ii", 3: "iii"}.get(doc.page, "i")
    num = roman if doc.page <= FRONT_PAGES else str(doc.page - FRONT_PAGES)
    canvas.drawCentredString(PAGE_W / 2, 0.5 * inch, num)
    canvas.setStrokeColor(BORDER)
    canvas.setLineWidth(0.5)
    canvas.line(MARGIN, 0.68 * inch, PAGE_W - MARGIN, 0.68 * inch)
    canvas.restoreState()

# ── Helpers ───────────────────────────────────────────────────────────────
def heading(text, level=0, style=None):
    st = style or (S["h1"] if level == 0 else S["h2"])
    key = "h_" + hashlib.md5(text.encode()).hexdigest()[:8]
    p = Paragraph(f'<a name="{key}"/><b>{text}</b>', st)
    p.bookmark_name = key
    p.bookmark_level = level
    p.bookmark_text = text
    p.bookmark_key = key
    return p

def h1(story, text):
    story.append(CondPageBreak(H1_ORPHAN))
