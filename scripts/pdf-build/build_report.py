def code_block(story, code_text, label=None):
    lines = code_text.strip("\n").split("\n")
    inner = []
    if label:
        inner.append(Paragraph(f"<b>{label}</b>", ParagraphStyle(
            "cl", parent=S["code"], textColor=TEXT_MUTED, spaceAfter=4)))
    for ln in lines:
        escaped = (ln.replace("&", "&").replace("<", "<")
                   .replace(">", ">").replace(" ", " "))
        inner.append(Paragraph(escaped if escaped else " ", S["code"]))
    box = Table([[inner]], colWidths=[AVAIL_W * 0.94])
    box.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.white),
        ("LINEBEFORE", (0, 0), (0, -1), 2.5, ICON),
        ("BOX", (0, 0), (-1, -1), 0.5, BORDER),
        ("LEFTPADDING", (0, 0), (-1, -1), 12),
        ("RIGHTPADDING", (0, 0), (-1, -1), 10),
        ("TOPPADDING", (0, 0), (-1, -1), 8),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
    ]))
    story.append(Spacer(1, 10))
    story.extend(safe_keep([box]))
    story.append(Spacer(1, 10))

